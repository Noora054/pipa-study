function loadState() {
  try {
    const saved = JSON.parse(localStorage.getItem(stateKey) || "{}");
    return { started: saved.started || {}, weeks: saved.weeks || {}, notes: saved.notes || {} };
  } catch {
    return { started: {}, weeks: {}, notes: {} };
  }
}

function saveState() {
  localStorage.setItem(stateKey, JSON.stringify(state));
  updateProgress();
}

function renderCards(filter = "") {
  grid.innerHTML = "";
  const query = filter.trim().toLowerCase();
  const visible = works.filter(work => `${work.title} ${work.type} ${work.hook} ${work.keywords} ${work.tags.join(" ")}`.toLowerCase().includes(query));
  emptyState.hidden = visible.length > 0;

  visible.forEach((work, order) => {
    const node = cardTemplate.content.cloneNode(true);
    const card = node.querySelector(".work-card");
    card.style.animationDelay = `${order * 45}ms`;
    if (state.started[work.id]) card.classList.add("is-started");
    node.querySelector(".work-index").textContent = work.index;
    node.querySelector(".work-status").textContent = state.started[work.id] ? "研习中" : "尚未启动";
    node.querySelector(".work-type").textContent = work.type;
    node.querySelector(".work-title").textContent = work.title;
    node.querySelector(".work-hook").textContent = work.hook;
    const tagRow = node.querySelector(".tag-row");
    work.tags.forEach(tag => {
      const span = document.createElement("span");
      span.className = "tag";
      span.textContent = tag;
      tagRow.append(span);
    });
    node.querySelector(".card-action").addEventListener("click", () => openWork(work.id));
    grid.append(node);
  });
}

function renderPath() {
  const list = document.querySelector("#pathList");
  list.innerHTML = studyPath.map(([week, title, output]) => `
    <article class="path-item">
      <span class="path-week">W${week}</span>
      <h3>${title}</h3>
      <p>${output}</p>
      <label class="path-check" title="标记本周完成">
        <input type="checkbox" data-week="${week}" ${state.weeks[week] ? "checked" : ""} />
        <span aria-hidden="true"></span>
        <span class="sr-only">第${Number(week)}周已完成</span>
      </label>
    </article>
  `).join("");
  list.querySelectorAll("input[data-week]").forEach(input => {
    input.addEventListener("change", event => {
      state.weeks[event.target.dataset.week] = event.target.checked;
      saveState();
    });
  });
}

